/** Günün ayeti: tarihten türeyen sabit bir sıra. */
export function ayahOfDay(date = new Date()) {
  const day = Math.floor(
    Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000)
  return AYAHS[day % AYAHS.length]
}
